-- +goose Up
-- Coded diagnoses for analytics (SAL-19, docs/plans/analytics.md §3, ADR 0012):
--   - diagnosis_group, diagnosis_group_range, diagnosis_group_name: our own diagnosis groups on ICD-10 code ranges
--     (appendix A), reference data with no personal data. A range is inclusive and compared on a code's first
--     length(from_code) characters. The names are ours, never WHO's titles, in the ten languages, unreviewed until
--     the doctor partner reviews them in the term review panel (a term reviewer, 00039).
--   - place: the geography of a clinic's location (ANA-3): the Federation as an entity with its ten cantons,
--     Republika Srpska and Brcko District as regions that are their own entity (parent NULL), ISO 3166-2:BA codes;
--     and 143 municipalities and cities (Wikidata items, CC0, fetched 2026-11-12; the composite cities Sarajevo
--     and Istocno Sarajevo left out for their municipalities, one duplicate item of Banja Luka dropped). Names are
--     proper nouns in the local language, in Latin and Cyrillic script (the Latin from the Serbian Cyrillic
--     label, transliterated). No personal data.
--   - condition: FHIR Condition, one per filled coded field of a signed document (category
--     encounter-diagnosis). The clinic's scope and the patient's own scope see it (as document_draft, 00031 and
--     00038). Written in the signing transaction, never updated or deleted by the application.
--   - salus_stats: the aggregate builds' role (as salus_retention, 00014): BYPASSRLS, owner of nothing, its own
--     login (STATS_DATABASE_URL, only cmd/worker); SELECT per column on the sources only, never a name, a contact
--     detail or a field value. The aggregate tables grant it their writes (ANA-2, ANA-3).
--   - The backfill: every coded value of a document signed before this migration becomes a Condition,
--     unconfirmed (nobody confirmed it), which analytics does not count.
-- NULLIF: an unset setting reads as '' on a pooled connection and must match nothing.

CREATE TABLE diagnosis_group (
    position integer NOT NULL UNIQUE,
    code text NOT NULL PRIMARY KEY CHECK (code ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    parent_code text REFERENCES diagnosis_group (code)
);

CREATE TABLE diagnosis_group_range (
    group_code text NOT NULL REFERENCES diagnosis_group (code),
    from_code text NOT NULL CHECK (from_code ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'),
    to_code text NOT NULL CHECK (to_code ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'),
    PRIMARY KEY (group_code, from_code),
    CONSTRAINT diagnosis_group_range_order CHECK (length(from_code) = length(to_code) AND from_code <= to_code)
);

CREATE TABLE diagnosis_group_name (
    updated_at timestamptz DEFAULT now() NOT NULL,
    reviewed_at timestamptz,
    reviewed_by uuid REFERENCES account (id),
    version_id integer DEFAULT 1 NOT NULL CHECK (version_id > 0),
    language language NOT NULL,
    review_status review_status DEFAULT 'unreviewed' NOT NULL,
    group_code text NOT NULL REFERENCES diagnosis_group (code),
    text text NOT NULL CHECK (btrim(text) <> ''),
    note text CHECK (note <> ''),
    PRIMARY KEY (group_code, language),
    CONSTRAINT diagnosis_group_name_reviewed_has_date CHECK (review_status = 'unreviewed' OR reviewed_at IS NOT NULL)
);

GRANT SELECT ON diagnosis_group, diagnosis_group_range, diagnosis_group_name TO salus_app;
-- A reviewer edits a name and reviews it; never a group, a range or a language.
GRANT UPDATE (updated_at, reviewed_at, reviewed_by, version_id, review_status, note, text) ON diagnosis_group_name TO salus_app;

CREATE TABLE place (
    id text NOT NULL PRIMARY KEY CHECK (id ~ '^(Q[0-9]+|BA-[0-9A-Z]{2,3})$'),
    kind text NOT NULL CHECK (kind IN ('entity', 'region', 'city')),
    parent_id text REFERENCES place (id),
    name_latn text NOT NULL CHECK (btrim(name_latn) <> ''),
    name_cyrl text NOT NULL CHECK (btrim(name_cyrl) <> ''),
    CONSTRAINT place_parent CHECK ((kind <> 'entity' OR parent_id IS NULL) AND (kind <> 'city' OR parent_id IS NOT NULL))
);

CREATE INDEX place_parent_id ON place (parent_id);

GRANT SELECT ON place TO salus_app;

CREATE TABLE condition (
    id uuid DEFAULT gen_random_uuid() NOT NULL PRIMARY KEY,
    created_at timestamptz DEFAULT now() NOT NULL,
    updated_at timestamptz DEFAULT now() NOT NULL,
    recorded_at timestamptz NOT NULL,
    organization_id uuid NOT NULL REFERENCES organization (id),
    patient_id uuid NOT NULL REFERENCES patient (id),
    encounter_id uuid NOT NULL REFERENCES encounter (id),
    document_draft_id uuid NOT NULL REFERENCES document_draft (id),
    practitioner_role_id uuid NOT NULL,
    version_id integer DEFAULT 1 NOT NULL,
    field_key text NOT NULL,
    code_system text DEFAULT 'http://hl7.org/fhir/sid/icd-10' NOT NULL CHECK (code_system = 'http://hl7.org/fhir/sid/icd-10'),
    code text NOT NULL CHECK (code ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'),
    verification_status text NOT NULL CHECK (verification_status IN ('confirmed', 'unconfirmed')),
    CONSTRAINT condition_document_field_key UNIQUE (document_draft_id, field_key),
    CONSTRAINT condition_practitioner_role_fkey FOREIGN KEY (practitioner_role_id, organization_id)
        REFERENCES practitioner_role (id, organization_id)
);

-- A clinic's Conditions over a time range (the aggregate builds); a patient's (their record).
CREATE INDEX condition_organization_recorded_at ON condition (organization_id, recorded_at);
CREATE INDEX condition_patient_id ON condition (patient_id);
CREATE INDEX condition_encounter_id ON condition (encounter_id);

ALTER TABLE condition ENABLE ROW LEVEL SECURITY;
CREATE POLICY condition_clinic ON condition
    USING (NULLIF(current_setting('app.patient_id', true), '') IS NULL
           AND NULLIF(current_setting('app.account_id', true), '') IS NULL
           AND NULLIF(current_setting('app.video_room', true), '') IS NULL
           AND organization_id = NULLIF(current_setting('app.organization_id', true), '')::uuid);
CREATE POLICY condition_own ON condition FOR SELECT
    USING (NULLIF(current_setting('app.video_room', true), '') IS NULL
           AND patient_id = NULLIF(current_setting('app.patient_id', true), '')::uuid);

-- Written once, with the signature; a signed document never changes, so neither do its Conditions.
GRANT SELECT, INSERT ON condition TO salus_app;

