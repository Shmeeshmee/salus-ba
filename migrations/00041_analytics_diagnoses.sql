-- The backfill: the coded values of the documents already signed, unconfirmed. Signing refused malformed codes,
-- so every value matches the check; the WHERE clause keeps the migration safe if one does not (it is then left
-- out rather than failing the migration). Recorded when signed, by the signer.
INSERT INTO condition (recorded_at, organization_id, patient_id, encounter_id, document_draft_id, practitioner_role_id,
                       field_key, code, verification_status)
SELECT d.signed_at, e.organization_id, e.patient_id, e.id, d.id, d.signer_role_id, f->>'key', f->>'value', 'unconfirmed'
FROM document_draft d
JOIN encounter e ON e.id = d.encounter_id
CROSS JOIN LATERAL jsonb_array_elements(d.fields) AS f
WHERE d.status = 'final'
  AND f->>'type' = 'coded'
  AND f->>'value' ~ '^[A-Z][0-9]{2}(\.[0-9A-Z]{1,4})?$'
ON CONFLICT (document_draft_id, field_key) DO NOTHING;
